-- ① ログインID列を追加（任意・一意・NULL許容）
ALTER TABLE users ADD COLUMN IF NOT EXISTS login_id TEXT;

-- ② ログインIDに一意インデックスを作成
--    NULL は重複OKなので、既存ユーザーへの影響なし
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_login_id
  ON users(login_id)
  WHERE login_id IS NOT NULL;

